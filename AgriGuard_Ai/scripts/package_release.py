"""Build a release archive that excludes the reproducible, machine-local junk.

    python scripts/package_release.py

Why this script exists
----------------------
The archive that was handed in for review contained a complete Windows
virtualenv: 37,843 files, roughly 1 GB uncompressed, with
`.venv/pyvenv.cfg` pointing at `C:\\Users\\...\\Python311`. It cannot work on
the reviewer's machine, it doubled the download, and it buried the 60 files
that actually matter. `.gitignore` already lists `.venv/`, `.cache/` and
`.pytest_cache/`, but an archive built by dragging the folder into WinRAR
never reads `.gitignore` - which is exactly how that happened.

So the exclusion list below is enforced here, in code, at the moment the
archive is written.

What is excluded, and why it is safe to exclude
-----------------------------------------------
    .venv/, venv/, env/   Rebuilt by `pip install -r requirements.txt`.
    .cache/               Regenerated by scripts/prepare_crop_dataset.py from
                          the PlantVillage download.
    .pytest_cache/        Test-run scratch.
    __pycache__/, *.pyc   Recompiled on import.
    dist/                 This script's own output.

What is deliberately NOT excluded, even though .gitignore ignores it
-------------------------------------------------------------------
`data/irrigation_data.csv` and `data/crop_health/` are both regenerable, and
ignoring them keeps the repository light, but a review pack that ships without
the data cannot be tested by the person receiving it. The images are the single
largest thing in the archive (~115 MB) and are included for that reason. Pass
`--with-dataset-ignored` to produce the slim archive instead, for a handover
where the recipient is expected to run the preparation scripts first.

Verification
------------
After building, the script re-opens the archive it just wrote and asserts that
not one excluded path made it in, then prints the file count and both on-disk
and uncompressed size. It does not run the test suite - the archive is just
files - so run this in the extracted copy before handing it over:

    python -m pytest -q
    python scripts/audit_stage3.py

Both must be green. An archive whose docs disagree with its own model metrics
will fail `tests/test_docs_consistency.py`, which is the failure mode this
packaging step is meant to be paired with.
"""

import argparse
import fnmatch
import os
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from agriguard.config import PROJECT_ROOT  # noqa: E402
from agriguard.version import __version__  # noqa: E402

DIST_DIR = PROJECT_ROOT / "dist"

#: Directory names skipped anywhere in the tree.
EXCLUDED_DIRS = {
    ".venv",
    "venv",
    "env",
    ".cache",
    ".pytest_cache",
    "__pycache__",
    ".git",
    "dist",
    ".mypy_cache",
    ".ruff_cache",
}

#: Filename globs skipped anywhere in the tree.
EXCLUDED_GLOBS = ["*.pyc", "*.pyo", "*.pyd", ".DS_Store", "Thumbs.db"]

#: Top-level entries dropped only with --with-dataset-ignored. Reproducible,
#: but required for a reviewer to reproduce the results.
DATASET_ENTRIES = {"data/irrigation_data.csv", "data/crop_health"}


def is_excluded(rel_path: str, drop_dataset: bool) -> bool:
    """True when a project-relative POSIX path must not go in the archive.

    Matched against the relative path with `/` separators so the same rules
    apply on Windows and Linux, and so a directory can be matched by prefix
    (`data/crop_health`) as well as by name.
    """
    parts = rel_path.split("/")
    if any(part in EXCLUDED_DIRS for part in parts[:-1]):
        return True
    if parts[-1] in EXCLUDED_DIRS:
        return True
    if any(fnmatch.fnmatch(parts[-1], pattern) for pattern in EXCLUDED_GLOBS):
        return True
    if drop_dataset and rel_path in DATASET_ENTRIES:
        return True
    return False


def collect_files(root: Path, drop_dataset: bool):
    """Every file to include, as (absolute path, archive-relative POSIX path)."""
    collected = []
    for dirpath, dirnames, filenames in os.walk(root):
        current = Path(dirpath)
        # Pruning here rather than filtering afterwards: it also stops os.walk
        # from descending into .venv at all, which is the difference between a
        # few seconds and walking 37,843 files.
        dirnames[:] = [
            name
            for name in dirnames
            if name not in EXCLUDED_DIRS
            and not (drop_dataset and (current / name) == root / "data" / "crop_health")
        ]
        for filename in filenames:
            absolute = current / filename
            relative = absolute.relative_to(root).as_posix()
            if is_excluded(relative, drop_dataset):
                continue
            collected.append((absolute, relative))
    return sorted(collected, key=lambda item: item[1])


def verify_archive(archive: Path, drop_dataset: bool):
    """Re-open the written archive and prove the exclusions actually held.

    The build path and the exclusion rules live in the same module, so a rule
    that silently stopped matching would never be caught by inspecting the
    build code alone. Re-reading what was written is the only check that
    matters here.
    """
    with zipfile.ZipFile(archive) as handle:
        names = handle.namelist()

    leaked = sorted(name for name in names if is_excluded(name, drop_dataset))
    if leaked:
        raise SystemExit(
            "packaging failed: excluded paths reached the archive:\n  "
            + "\n  ".join(leaked[:20])
        )
    return names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="output .zip path (default: dist/AgriGuard_AI_<version>.zip)",
    )
    parser.add_argument(
        "--with-dataset-ignored",
        action="store_true",
        help="also drop the irrigation CSV and the prepared crop images",
    )
    args = parser.parse_args()

    out = args.out or (DIST_DIR / f"AgriGuard_AI_{__version__}.zip")
    out = out if out.is_absolute() else PROJECT_ROOT / out
    out.parent.mkdir(parents=True, exist_ok=True)

    if not (PROJECT_ROOT / "models" / "irrigation_model.json").exists():
        raise SystemExit(
            "refusing to package: models/irrigation_model.json is missing. "
            "Run scripts/train_irrigation.py first - without it the API silently "
            "falls back to rules and the archive ships a service that never uses "
            "the model it was reviewed for."
        )

    drop_dataset = args.with_dataset_ignored
    files = collect_files(PROJECT_ROOT, drop_dataset)
    if not files:
        raise SystemExit("refusing to package: no files matched")

    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as handle:
        for absolute, relative in files:
            handle.write(absolute, arcname=f"AgriGuard_AI/{relative}")

    names = verify_archive(out, drop_dataset)
    # Summed from `files`, not from the archive member names: the members are
    # prefixed with the project folder ("AgriGuard_AI/...") so that the archive
    # unpacks into one directory instead of scattering into the cwd.
    uncompressed = sum(absolute.stat().st_size for absolute, _ in files)
    on_disk = out.stat().st_size

    print(f"archive : {out}")
    print(f"files   : {len(names)}")
    print(f"on disk : {on_disk / (1024 * 1024):.1f} MiB")
    print(f"source  : {uncompressed / (1024 * 1024):.1f} MiB uncompressed")
    if drop_dataset:
        print("dataset : EXCLUDED - the recipient must run the preparation scripts")
    print()
    print("verify in the extracted copy before handing it over:")
    print("    python -m pytest -q")
    print("    python scripts/audit_stage3.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

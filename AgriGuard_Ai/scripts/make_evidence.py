"""Generate the text evidence files under evidence/.

    python scripts/make_evidence.py

What this script can and cannot do
---------------------------------
It runs the real commands and captures their real output, so the text evidence
is genuine. It does NOT fabricate screenshots. Where a screenshot matters
(terminal windows, the Swagger UI, a live dashboard) it writes a numbered
instruction file telling the student exactly what to capture, so the evidence
folder is honest about what is machine-generated and what is manual.
"""

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from agriguard.config import (  # noqa: E402
    CROP_HEALTH_DIR,
    EVIDENCE_DIR,
    EXAMPLES_DIR,
    IRRIGATION_CSV,
    IRRIGATION_MODEL_PATH,
    PROJECT_ROOT,
)

BANNER = (
    "AUTO-GENERATED by scripts/make_evidence.py - every number below is the real\n"
    "output of the command shown at the top of the file.\n"
)


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"{BANNER}generated: {datetime.now(timezone.utc).isoformat()}\n\n"
    path.write_text(header + text, encoding="utf-8")
    return path


def run(args, label):
    result = subprocess.run(
        [sys.executable, *args],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
    )
    body = f"$ python {' '.join(args)}\n\n"
    body += result.stdout
    if result.stderr.strip():
        body += "\n--- stderr ---\n" + result.stderr
    body += f"\nexit code: {result.returncode}\n"
    return body


def examples_summary(path: Path, kind: str) -> str:
    """Render examples/*.json as a readable table.

    make_examples.py only prints "wrote N examples", so without this the
    prediction evidence files contain no predictions at all. A reviewer who cannot
    run the code should still be able to read the actual outputs.
    """
    if not path.exists():
        return f"\n({path.name} not found)\n"

    data = json.loads(path.read_text(encoding="utf-8"))
    lines = ["", f"=== {path.name} ===", f"generated at: {data.get('generated_at')}"]
    examples = data.get("examples", [])
    if not examples:
        return "\n(no examples in file)\n"

    if kind == "irrigation":
        for ex in examples:
            pred = (ex.get("response") or {}).get("prediction", {})
            score = pred.get("prediction_score")
            history = pred.get("history_used")
            needed = "WATER" if pred.get("irrigation_needed") else "no water"
            request = ex.get("request", {})
            print_hint = ""
            if score is not None:
                print_hint = f" score={score:.4f}"
            if history is not None:
                print_hint += f" history_used={history}"
            lines.append(f"  {ex.get('name')}")
            lines.append(
                f"      soil_moisture={request.get('soil_moisture')}"
                f" crop={request.get('crop_type')!r} -> {needed}{print_hint}"
            )
    else:
        for ex in examples:
            pred = (ex.get("response") or {}).get("prediction", {})
            truth = ex.get("ground_truth")
            verdict = "correct" if ex.get("correct") else "WRONG"
            lines.append(
                f"  {ex.get('name')}  {ex.get('request', {}).get('filename')}"
                f"  truth={truth} -> {pred.get('label')}"
                f" conf={pred.get('confidence')} [{verdict}]"
            )
    lines.append("")
    lines.append("  full request/response JSON: " + path.as_posix())
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=EVIDENCE_DIR)
    args = parser.parse_args()
    out = args.out
    out.mkdir(parents=True, exist_ok=True)

    written = []

    # 01 dataset structure
    lines = ["IRRIGATION DATASET", f"file: {IRRIGATION_CSV.name}", ""]
    import pandas as pd

    frame = pd.read_csv(IRRIGATION_CSV)
    lines.append(f"rows: {len(frame)}")
    lines.append(f"columns: {list(frame.columns)}")
    lines.append(f"time range: {frame['timestamp'].min()} -> {frame['timestamp'].max()}")
    lines.append(f"devices: {sorted(frame['device_id'].unique())}")
    lines.append(f"plots: {sorted(frame['plot_id'].unique())}")
    lines.append(
        f"irrigation_event positives: {int(frame['irrigation_event'].sum())} "
        f"({frame['irrigation_event'].mean():.2%})"
    )
    lines.append(f"rows with NPK: {int(frame['npk_n'].notna().sum())}")
    lines += ["", "SYNTHETIC PROTOTYPE DATA - NOT REAL FIELD MEASUREMENTS.", "", frame.head(5).to_string(index=False)]
    written.append(write(out / "01_dataset_structure.txt", "\n".join(lines)))

    # 02/03 irrigation training + evaluation
    written.append(write(out / "02_irrigation_training.txt", run(["scripts/train_irrigation.py", "--report-only"], "report")))
    written.append(write(out / "03_irrigation_evaluation.txt", run(["scripts/evaluate_models.py"], "evaluate")))

    # 04 irrigation prediction
    written.append(
        write(
            out / "04_irrigation_prediction.txt",
            run(["scripts/make_examples.py"], "examples")
            + examples_summary(EXAMPLES_DIR / "irrigation_prediction.json", "irrigation"),
        )
    )

    # 04b decision boundaries quoted in the docs
    written.append(
        write(out / "04b_decision_boundaries.txt", run(["scripts/decision_boundaries.py"], "boundaries"))
    )

    # 05 crop dataset
    stats_path = CROP_HEALTH_DIR / "dataset_stats.json"
    if stats_path.exists():
        stats = json.loads(stats_path.read_text(encoding="utf-8"))
        summary = {
            "total_images": stats["total_images"],
            "counts": stats["counts"],
            "source": stats["source"],
            "split_fractions": stats["split_fractions"],
            "split_seed": stats["split_seed"],
            "per_class_cap": stats["per_class_cap"],
            "per_original_class": stats["per_original_class"],
        }
        written.append(write(out / "05_crop_dataset.txt", json.dumps(summary, indent=2)))

    # 06/07 crop training + evaluation
    weights = PROJECT_ROOT / "models" / "crop_health_model.pth"
    if weights.exists():
        written.append(write(out / "06_crop_training.txt", run(["scripts/train_crophealth.py", "--report-only"], "report")))
        written.append(write(out / "07_crop_evaluation.txt", run(["scripts/evaluate_models.py"], "evaluate")))

    # 08 confusion matrices
    evaluation = PROJECT_ROOT / "models" / "evaluation_summary.json"
    if evaluation.exists():
        data = json.loads(evaluation.read_text(encoding="utf-8"))
        text = "IRRIGATION confusion matrix (rows = true, cols = predicted)\n"
        irrigation = data.get("irrigation") or {}
        if irrigation:
            matrix = irrigation["confusion_matrix"]
            text += f"labels: {matrix['labels']}\n"
            for label, row in zip(matrix["labels"], matrix["values"]):
                text += f"  true {label}: {row}\n"
            text += (
                f"  TN={matrix['tn']} FP={matrix['fp']} "
                f"FN={matrix['fn']} TP={matrix['tp']}\n"
            )
        text += "\nCROP-HEALTH confusion matrix (rows = true, cols = predicted)\n"
        crop = data.get("crop_health") or {}
        if crop:
            matrix = crop["confusion_matrix"]
            text += f"labels: {matrix['labels']}\n"
            for label, row in zip(matrix["labels"], matrix["values"]):
                text += f"  true {label}: {row}\n"
        written.append(write(out / "08_confusion_matrix.txt", text))

    # 09 crop prediction
    written.append(
        write(
            out / "09_crop_prediction.txt",
            run(["scripts/make_examples.py"], "examples")
            + examples_summary(EXAMPLES_DIR / "crop_health_prediction.json", "crop_health"),
        )
    )

    # 10/11 live API transcripts
    written.append(write(out / "10_irrigation_api.txt", run(["scripts/api_demo.py", "--endpoint", "irrigation"], "api demo")))
    written.append(write(out / "11_crop_health_api.txt", run(["scripts/api_demo.py", "--endpoint", "crop-health"], "api demo")))

    # 12 pytest
    written.append(write(out / "12_pytest_results.txt", run(["-m", "pytest", "-v"], "pytest")))

    # 13 exploratory analysis: correlations, cross-validation, hypothesis tests
    written.append(
        write(out / "13_eda_analysis.txt", run(["scripts/eda.py"], "eda"))
    )

    print(f"wrote {len(written)} evidence files to {out}")
    for path in written:
        print(f"  {path.name}")


if __name__ == "__main__":
    main()
